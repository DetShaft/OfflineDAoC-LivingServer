# Registers a Windows scheduled task that runs Watch-Releases.ps1 every 30 minutes.
# Current user, only while that user is logged on, least privilege. No administrator prompt.
# PowerShell 5.1 compatible.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\smoke\Register-SmokeTask.ps1
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\smoke\Register-SmokeTask.ps1 -StagingRoot 'E:\LivingServerSmoke\staging'
param(
    [string]$LiveRoot = 'E:\Offline DAOC',
    [string]$StagingRoot = '',
    [string]$Zone = 'Gotar',
    [string]$TaskName = 'LivingServerWorldEntrySmoke'
)

$ErrorActionPreference = 'Stop'
if ($env:OS -ne 'Windows_NT') {
    Write-Host 'BLOCKED: Register-SmokeTask.ps1 registers a Windows scheduled task. Run it on Jay-PC.'
    exit 2
}
if (!$env:LOCALAPPDATA) {
    Write-Host 'BLOCKED: LOCALAPPDATA is not set.'
    exit 2
}

$watch = Join-Path $PSScriptRoot 'Watch-Releases.ps1'
if (!(Test-Path -LiteralPath $watch)) {
    Write-Host "BLOCKED: $watch is missing."
    exit 2
}
if (!$StagingRoot) { $StagingRoot = Join-Path $env:LOCALAPPDATA 'LivingServerSmoke\staging' }

$homeDir = Join-Path $env:LOCALAPPDATA 'LivingServerSmoke'
if (!(Test-Path -LiteralPath $homeDir)) { New-Item -ItemType Directory -Path $homeDir -Force | Out-Null }
$launcher = Join-Path $homeDir 'run-watcher.ps1'
$quote = { param($t) "'" + ($t -replace "'", "''") + "'" }
$body = @(
    '# Generated by Register-SmokeTask.ps1. Re-run that script after you move the repo.',
    '& ' + (& $quote $watch) + ' -LiveRoot ' + (& $quote $LiveRoot) + ' -StagingRoot ' + (& $quote $StagingRoot) + ' -Zone ' + (& $quote $Zone),
    'exit $LASTEXITCODE'
)
Set-Content -LiteralPath $launcher -Value $body -Encoding UTF8
Write-Host "Launcher: $launcher"

$argument = '-NoProfile -ExecutionPolicy Bypass -File "' + $launcher + '"'
try {
    $action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument $argument
    $start = (Get-Date).Date
    $trigger = New-ScheduledTaskTrigger -Once -At $start -RepetitionInterval (New-TimeSpan -Minutes 30) -RepetitionDuration (New-TimeSpan -Days 9999)
    $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew
    $user = $env:USERNAME
    if ($env:USERDOMAIN) { $user = $env:USERDOMAIN + '\' + $env:USERNAME }
    $principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
    Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Force | Out-Null
    Write-Host "Registered scheduled task '$TaskName' every 30 minutes, only while $user is logged on."
    exit 0
} catch {
    Write-Host "ScheduledTask cmdlet failed: $($_.Exception.Message)"
    Write-Host 'Trying schtasks.'
}

$tr = 'powershell.exe -NoProfile -ExecutionPolicy Bypass -File \"' + $launcher + '\"'
& "$env:SystemRoot\System32\schtasks.exe" /Create /F /TN $TaskName /SC MINUTE /MO 30 /IT /RL LIMITED /TR $tr
if ($LASTEXITCODE -ne 0) {
    Write-Host 'BLOCKED: could not register the scheduled task without an administrator.'
    exit 2
}
Write-Host "Registered scheduled task '$TaskName' (schtasks /IT, every 30 minutes, current user)."
exit 0
